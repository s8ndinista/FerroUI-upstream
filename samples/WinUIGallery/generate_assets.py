#!/usr/bin/env python3
"""Copy and register the pinned Gallery's original control-detail image assets."""

import argparse
import hashlib
import json
from pathlib import Path
import subprocess

SOURCE_COMMIT = "14061eeac21c38ae99f302edf3d9136d4f652c4c"
METADATA = "WinUIGallery/SampleSupport/Data/ControlInfoData.json"


def outputs(upstream):
    commit = subprocess.check_output(["git", "-C", str(upstream), "rev-parse", "HEAD"], text=True).strip()
    if commit != SOURCE_COMMIT:
        raise ValueError(f"Expected Gallery {SOURCE_COMMIT}, found {commit}")
    if subprocess.run(["git", "-C", str(upstream), "diff", "--quiet", "HEAD", "--", "WinUIGallery"], check=False).returncode:
        raise ValueError("Pinned Gallery source files have local changes")
    metadata = json.loads((upstream / METADATA).read_text(encoding="utf-8-sig"))
    paths = sorted({item.get("ImagePath") or "ms-appx:///Assets/ControlImages/Placeholder.png"
                    for group in metadata["Groups"] for item in group["Items"]})
    root = upstream / "WinUIGallery"
    candidates = list((root / "Assets/ControlImages").glob("*.png"))
    folded = {str(path.relative_to(root)).casefold(): path for path in candidates}
    if len(folded) != len(candidates):
        raise ValueError("Ambiguous Windows image-path casing")
    files = {}
    registrations = []
    output = {}
    for uri in paths:
        if not uri.startswith("ms-appx:///Assets/ControlImages/"):
            raise ValueError(f"Unexpected image URI: {uri}")
        registered = uri.removeprefix("ms-appx:///")
        original = root / registered
        if not original.is_file():
            original = folded.get(registered.casefold())
        if original is None or not original.is_file():
            raise ValueError(f"Missing image: {uri}")
        relative = original.relative_to(root).as_posix()
        payload = original.read_bytes()
        output[relative] = payload
        record = files.setdefault(relative, {
            "source": "WinUIGallery/" + relative,
            "path": "samples/WinUIGallery/" + relative,
            "sha256": hashlib.sha256(payload).hexdigest(),
            "size_bytes": len(payload),
            "registered_paths": [],
            "source_uris": [],
        })
        record["registered_paths"].append(registered)
        record["source_uris"].append(uri)
        registrations.append(f'    ({json.dumps(registered)}, include_bytes!({json.dumps(relative)}) as &[u8]),')
        if registered != relative:
            record["registered_paths"].append(relative)
            registrations.append(f'    ({json.dumps(relative)}, include_bytes!({json.dumps(relative)}) as &[u8]),')
    output["assets_data.rs"] = ("// Generated by generate_assets.py; do not edit by hand.\n"
        "// Original Microsoft WinUI Gallery PNG bytes; see NOTICE.md and assets-manifest.json.\n"
        "#[rustfmt::skip]\n"
        "pub(crate) static ASSETS: &[(&str, &[u8])] = &[\n" + "\n".join(registrations) + "\n];\n").encode()
    manifest = {
        "schema_version": 1,
        "source_repository": "https://github.com/microsoft/WinUI-Gallery",
        "source_commit": SOURCE_COMMIT,
        "license": "MIT; Copyright (c) Microsoft Corporation. All rights reserved. See NOTICE.md.",
        "metadata_source": METADATA,
        "metadata_sha256": hashlib.sha256((upstream / METADATA).read_bytes()).hexdigest(),
        "assembly": "WinUIGallery",
        "uri_scheme": "ferres",
        "path_policy": "Original filenames and bytes are preserved. Registered source paths explicitly retain Windows case differences as aliases.",
        "assets": list(files.values()),
    }
    output["assets-manifest.json"] = (json.dumps(manifest, indent=2) + "\n").encode()
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("upstream", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).parent
    generated = outputs(args.upstream)
    for relative, payload in generated.items():
        destination = root / relative
        if args.check:
            if not destination.is_file() or destination.read_bytes() != payload:
                raise SystemExit(f"{relative} differs; run generate_assets.py without --check")
        else:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(payload)
    print(f"Gallery assets are reproducible: {len(generated) - 2} original image files")


if __name__ == "__main__":
    main()
